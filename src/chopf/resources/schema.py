"""
openAPIV3Schema generation for custom resources.

Since the lightkube v1 migration all resource and model classes are
msgspec Structs (or plain stdlib dataclasses for nested user models), so
schema generation is delegated to ``msgspec.json.schema()`` and then
post-processed into something kubernetes accepts as a CRD structural
schema:

- ``$defs``/``$ref`` are dereferenced and inlined (CRDs disallow them).
- ``anyOf: [T, null]`` collapses to ``T`` (``type: null`` is not allowed
  in structural schemas) and ``default: null`` is dropped.
- ``anyOf: [integer, string]`` collapses to ``integer`` — this preserves
  the historical treatment of ``IntOrString`` fields.
- ``format: date-time`` is restored for ``datetime.datetime`` fields
  (msgspec does not emit it) and plain-string ``Annotated`` metadata
  becomes the field description.
- Descriptions derived from the (huge) autogenerated docstrings of
  lightkube-provided models are stripped.
- ``metadata`` is always reduced to ``{'type': 'object'}`` — CRD schemas
  are not allowed to specify a detailed ObjectMeta.

The dereference/clean passes predate the msgspec migration; some code in
this file is based on https://github.com/Peter554/dc_schema (MIT License,
Copyright (c) 2022 Peter Byfield).

Resources:

https://www.brendanp.com/pretty-printing-with-kubebuilder/

https://kubernetes.io/docs/tasks/extend-kubernetes/custom-resources/custom-resource-definitions/

- Kubernetes JSONSchemaProps
    https://dev-k8sref-io.web.app/docs/common-definitions/jsonschemaprops-/

"""

from __future__ import annotations

import dataclasses
import datetime
import numbers
import types
import typing as t

import msgspec


def _schema_hook(type_) -> dict:
    """msgspec schema hook for types it cannot map to JSON schema."""
    # GenericStruct and friends are free-form dicts.
    if getattr(type_, '__schema_type__', None) is dict:
        return {'type': 'object'}
    raise NotImplementedError(f'no JSON schema for type: {type_!r}')


def get_schema(dc):
    raw = msgspec.json.schema(dc, schema_hook=_schema_hook)
    definitions = raw.pop('$defs', {})

    # Do not use docstrings for lightkube provided models as they are too large.
    for name in _lightkube_component_names(dc):
        if name in definitions:
            definitions[name].pop('description', None)

    # First dereference any nested definitions.
    # This is just a performance optimisation so we only dereference
    # each models once instead of repeating that for each reference.
    _dereference_schema(definitions, definitions)
    # Then dereference the actual schema.
    _dereference_schema(raw, definitions)
    # Then cleanup the schema into something that kubernetes agrees with.
    # TODO: is this still needed?
    _clean_schema(raw)

    schema = raw
    _fixup_schema(schema)
    _annotate_from_model(dc, schema, seen=set())

    # We are not allowed to specify a detailed ObjectMeta in crd.
    schema.setdefault('properties', {})['metadata'] = {'type': 'object'}

    # Explicit per-model schema configuration wins over derived data.
    if hasattr(dc, 'SchemaConfig'):
        annotation = getattr(dc.SchemaConfig, 'annotation', SchemaAnnotation())
        schema.update(annotation.schema())

    return schema


def _resolve_definition(name, definitions):
    ref_name = name.rpartition('/')[-1]
    definition = definitions[ref_name]
    return definition


def _dereference_schema(schema, definitions, parent=None, key=None):
    """Find and dereference objects in the given schema.

    '#/definitions/myElement' -> schema.definitions[myElement]
    """
    if hasattr(schema, 'items'):
        if list(schema.keys()) == ['$ref']:
            definition = _resolve_definition(schema['$ref'], definitions)
            schema.clear()
            schema.update(definition.items())
        else:
            for k, v in schema.items():
                if k == '$ref':
                    # print(f'{type(parent)} {key}: {k} -> {v}')
                    definition = _resolve_definition(v, definitions)
                    if isinstance(parent, dict):
                        parent[key] = definition
                    elif isinstance(parent, list):
                        parent[parent.index(key)] = definition
                    v = definition
                if isinstance(v, dict):
                    _dereference_schema(v, definitions, parent=schema, key=k)
                elif isinstance(v, list):
                    for i, d in enumerate(v):
                        _dereference_schema(d, definitions, parent=v, key=d)
                else:
                    # print(f'unhandled k: {k}; v: {v}; %s' % type(v))
                    pass


def _clean_schema(schema):
    """Clean the schema for use with kubernetes.

    Pydantic uses allOf to preserve some fields like title and description
    that would otherwise be overwritten by nested models.
    Kubernetes does not like that so we work around that by merging
    the nested model properties.


    We basically turn this:

    ```
    {
       'tokenSecretRef': {
          'title': 'Tokensecretref',
          'description': 'Some interesting field description.',
          'allOf': [{
             'title': 'SecretRef',
             'description': 'Some model docstring.',
             'type': 'object',
             'properties': {
                'name': {'title': 'Name', 'type': 'string'}, 'key': {'title': 'Key', 'type': 'string'}
             },
             'required': ['name']
          }]
       }
    }
    ```

    into this:

    ```
    {
       'tokenSecretRef': {
          'title': 'Tokensecretref',
          'description': 'Some interesting field description.',
          'type': 'object',
          'properties': {
             'name': {'title': 'Name', 'type': 'string'}, 'key': {'title': 'Key', 'type': 'string'}
          },
          required': ['name']
       }
    }
    ```
    """
    # print(f'### _clean_schema: {schema}')
    if hasattr(schema, 'items'):
        if 'allOf' in schema:
            # print(f'### _clean_schema allOf detected: {schema}')
            value = schema['allOf']
            # print(f'### _clean_schema value: {value}')
            if len(value) == 1:
                child = value[0]
                for k, v in child.items():
                    schema.setdefault(k, v)
                schema.pop('allOf')
            _clean_schema(schema)
        else:
            if isinstance(schema, dict):
                for k, v in schema.items():
                    _clean_schema(v)
            elif isinstance(schema, list):
                for i, d in enumerate(schema):
                    _clean_schema(d)


def _fixup_schema(node):
    """Recursive schema-level transforms (post dereference/cleanup)."""
    if isinstance(node, dict):
        any_of = node.get('anyOf')
        if isinstance(any_of, list):
            # Optional fields: drop the null branch; structural schemas do
            # not allow `type: null` and kubernetes treats every field as
            # nullable-ish anyway.
            non_null = [b for b in any_of if b != {'type': 'null'}]
            if len(non_null) != len(any_of):
                if len(non_null) == 1:
                    branch = non_null[0]
                    del node['anyOf']
                    for k, v in branch.items():
                        node.setdefault(k, v)
                else:
                    node['anyOf'] = non_null
            # IntOrString (Union[int, str]): keep the historical behavior
            # of treating it as int.
            any_of = node.get('anyOf')
            if isinstance(any_of, list) and len(any_of) == 2:
                branch_types = {b.get('type') for b in any_of if isinstance(b, dict)}
                if branch_types == {'integer', 'string'}:
                    del node['anyOf']
                    node.setdefault('type', 'integer')
        if 'default' in node and node['default'] is None:
            del node['default']
        if node.get('required') == []:
            del node['required']
        for v in node.values():
            _fixup_schema(v)
    elif isinstance(node, list):
        for item in node:
            _fixup_schema(item)


def _unwrap(type_):
    """Return (core_type, annotated_string_metadata) for a type hint.

    Strips ``Annotated`` (keeping the first plain-string metadata item)
    and ``Optional``.
    """
    meta = None
    while True:
        origin = t.get_origin(type_)
        if origin is t.Annotated:
            args = t.get_args(type_)
            type_ = args[0]
            for m in args[1:]:
                if isinstance(m, str) and meta is None:
                    meta = m
        elif origin in (t.Union, types.UnionType):
            args = [a for a in t.get_args(type_) if a is not types.NoneType]
            if len(args) == 1:
                type_ = args[0]
            else:
                break
        else:
            break
    return type_, meta


def _is_model(type_):
    return isinstance(type_, type) and (
        issubclass(type_, msgspec.Struct) or dataclasses.is_dataclass(type_)
    )


def _nested_model(type_):
    """The model class contained in a type hint, if any."""
    core, _ = _unwrap(type_)
    origin = t.get_origin(core)
    if origin in (list, set, frozenset, tuple):
        args = [a for a in t.get_args(core) if a is not Ellipsis]
        return _nested_model(args[0]) if args else None
    if origin is dict:
        args = t.get_args(core)
        return _nested_model(args[1]) if len(args) == 2 else None
    if _is_model(core):
        return core
    return None


def _type_hints(cls):
    try:
        return t.get_type_hints(cls, include_extras=True)
    except Exception:  # noqa: BLE001 - unresolvable hints (NameError, TypeError, ...)
        return {}


def _lightkube_component_names(root):
    """Possible $defs keys of lightkube-provided models reachable from root.

    msgspec names components ``cls.__name__`` and falls back to the
    fully-qualified ``module.qualname`` on name collisions (e.g. chopf's
    ObjectMeta vs lightkube's), so we cover both forms.
    """
    names = set()
    seen = set()
    stack = [root]
    while stack:
        cls = stack.pop()
        if id(cls) in seen:
            continue
        seen.add(cls)
        if cls.__module__.startswith('lightkube'):
            names.add(cls.__name__)
            names.add(f'{cls.__module__}.{cls.__qualname__}')
        for type_ in _type_hints(cls).values():
            nested = _nested_model(type_)
            if nested is not None:
                stack.append(nested)
    return names


def _annotate_from_model(cls, node, seen):
    """Model-level fixups that need the actual field types.

    Walks the (already inlined) schema in parallel with the model classes:
    - restores ``format: date-time`` for ``datetime.datetime`` fields
      (msgspec.json.schema does not emit it),
    - turns plain-string ``Annotated`` metadata into descriptions.
    """
    if id(cls) in seen or not isinstance(node, dict):
        return
    seen.add(id(cls))
    props = node.get('properties', {})
    for name, type_ in _type_hints(cls).items():
        if name not in props:
            continue
        core, meta = _unwrap(type_)
        if meta:
            props[name].setdefault('description', meta)
        if core is datetime.datetime:
            props[name].setdefault('format', 'date-time')
        nested = _nested_model(type_)
        if nested is not None:
            _annotate_from_model(nested, props[name], seen)


_Format = t.Literal[
    'date-time',
    'time',
    'date',
    'duration',
    'email',
    'idn-email',
    'hostname',
    'idn-hostname',
    'ipv4',
    'ipv6',
    'uuid',
    'uri',
    'uri-reference',
    'iri',
    'iri-reference',
]


@dataclasses.dataclass(frozen=True)
class SchemaAnnotation:
    """Explicit schema overrides via a model's ``SchemaConfig`` class.

    Note: ``msgspec.Meta`` in ``Annotated`` field metadata is the
    preferred mechanism for constraints (min/max, pattern, description,
    ...) — it is enforced on decode and rendered into the schema by
    msgspec itself. SchemaAnnotation remains for whole-model overrides.
    """

    title: str | None = None
    description: str | None = None
    examples: list[t.Any] | None = None
    deprecated: bool | None = None
    min_length: int | None = None
    max_length: int | None = None
    pattern: str | None = None
    format: _Format | None = None
    minimum: numbers.Number | None = None
    maximum: numbers.Number | None = None
    exclusive_minimum: numbers.Number | None = None
    exclusive_maximum: numbers.Number | None = None
    multiple_of: numbers.Number | None = None
    min_items: int | None = None
    max_items: int | None = None
    unique_items: bool | None = None

    def schema(self):
        key_map = {
            'min_length': 'minLength',
            'max_length': 'maxLength',
            'exclusive_minimum': 'exclusiveMinimum',
            'exclusive_maximum': 'exclusiveMaximum',
            'multiple_of': 'multipleOf',
            'min_items': 'minItems',
            'max_items': 'maxItems',
            'unique_items': 'uniqueItems',
        }
        return {
            key_map.get(k, k): v
            for k, v in dataclasses.asdict(self).items()
            if v is not None
        }
